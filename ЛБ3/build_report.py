def p(text='', role='body', bold=False, center=False, size=None, page=False):
    node = deepcopy(title if role == 'title' else heading if role == 'heading' else normal)
    pr = node.find('w:pPr', NS)
    if pr is None: pr=E.SubElement(node, tag('pPr'))
    for el in list(node):
        if el.tag != tag('pPr'): node.remove(el)
    for el in list(pr):
        if el.tag in [tag('outlineLvl'),tag('shd'),tag('keepNext'),tag('pageBreakBefore')]: pr.remove(el)
    if role in ['heading','title']:
        E.SubElement(pr,tag('keepNext'))
    if page: E.SubElement(pr,tag('pageBreakBefore'))
    if center or role == 'title':
        jc=pr.find('w:jc',NS)
        if jc is None: jc=E.SubElement(pr,tag('jc'))
        jc.set(tag('val'),'center')
    if role == 'code':
        for k in ['ind','jc']:
            el=pr.find('w:'+k,NS)
            if el is not None: pr.remove(el)
        E.SubElement(pr,tag('jc')).set(tag('val'),'left')
    r=E.SubElement(node,tag('r')); rp=E.SubElement(r,tag('rPr'))
    rf=E.SubElement(rp,tag('rFonts'))
    for k in ['ascii','hAnsi','cs','eastAsia']: rf.set(tag(k),'Liberation Mono' if role=='code' else 'Times New Roman')
    E.SubElement(rp,tag('sz')).set(tag('val'),str(int(2*(size or (9 if role=='code' else 14)))))
    if bold or role in ['title','heading']: E.SubElement(rp,tag('b'))
    for i,line in enumerate(text.split('\n')):
        if i: E.SubElement(r,tag('br'))
        t=E.SubElement(r,tag('t'));t.set('{http://www.w3.org/XML/1998/namespace}space','preserve');t.text=line
    body.append(node)
    return node

