from pathlib import Path
import csv
from docx import Document
from docx.shared import Cm, Pt, RGBColor
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
p=Path(__file__).resolve().parent
rows=list(csv.DictReader((p/'timings.csv').open()))
assert len(rows)==5 and all(r['insertion_ms'] for r in rows)
d=Document(); s=d.sections[0]; s.page_width=Cm(21); s.page_height=Cm(29.7)
s.top_margin=s.bottom_margin=Cm(1.8); s.left_margin=Cm(2); s.right_margin=Cm(1.5)
for name in ['Normal','Title','Heading 1','Heading 2']:
 st=d.styles[name]; st.font.name='Times New Roman'; st.font.size=Pt(12 if name=='Normal' else 16); st.font.color.rgb=RGBColor(0,0,0)
 st.paragraph_format.space_after=Pt(8)
d.styles['Normal'].paragraph_format.line_spacing=1.1
for st in d.styles:
 for el in list(st.element.iter(qn('w:pBdr'))): el.getparent().remove(el)
def para(t): d.add_paragraph(t)
def h(t): d.add_heading(t,1)
def page(): d.add_page_break()
def code(t,size=9):
 q=d.add_paragraph(); q.paragraph_format.line_spacing=1; q.paragraph_format.space_after=Pt(0)
 r=q.add_run(t); r.font.name='Liberation Mono'; r.font.size=Pt(size)
para('Образовательная организация __________________________')
para('Кафедра ____________________________________________')
for _ in range(3): para('')
d.add_paragraph('Отчёт по заданию 2','Title')
d.add_paragraph('Разработка и исследование алгоритмов сортировки и сложной рекурсии','Title')
para('Вариант 12')
for _ in range(3): para('')
para('Выполнил(а) ____________________    Группа __________')
para('Проверил(а) ________________________________________')
para('Город ____________________    2026')
page(); h('Постановка задачи')
para('Реализовать сортировку вставками массива типа float, быструю сортировку без рекурсии и рекурсивную сортировку методом Хоара. Проверить корректность на 50 случайных элементах и сравнить время работы на массивах из 1 000, 10 000, 100 000, 500 000 и 1 000 000 элементов.')
para('Для варианта 12 цифры номера подставляются в шаблон [1x0x0; 3x70x] слева направо: нижняя граница 11020, верхняя 31702. Все исходные случайные значения находятся в этом диапазоне. Массив хранится в std::vector<float>.')
h('Алгоритмы решения задачи')
d.add_heading('Сортировка вставками',2)
para('Элементы слева от текущего индекса i уже упорядочены. Текущий элемент сохраняется в key. Все предшествующие элементы, превышающие key, сдвигаются на одну позицию вправо. Затем key записывается в освободившуюся позицию. Процесс повторяется до конца массива. Равные элементы не переставляются друг относительно друга.')
para('В лучшем случае время линейное, в среднем и худшем — квадратичное. Дополнительная память постоянная. Алгоритм устойчивый.')
d.add_heading('Разбиение Хоара',2)
para('Опорным выбирается значение среднего элемента текущего диапазона. Левый указатель ищет элемент не меньше опорного, правый — не больше опорного. Если указатели ещё не пересеклись, элементы меняются местами. При пересечении возвращается граница j: дальнейшей сортировке подлежат диапазоны [left; j] и [j + 1; right]. Опорный элемент не обязан находиться на окончательной позиции.')
d.add_heading('Две реализации быстрой сортировки',2)
para('Рекурсивная реализация вызывает себя для двух частей и завершается при left >= right. Реализация без рекурсии хранит границы ещё не обработанных частей в явном стеке. Обе используют одинаковое разбиение и правило выбора опорного элемента, поэтому сравнивается прежде всего способ управления обходом.')
para('Среднее время быстрой сортировки — O(N log N), худшее — O(N²). Для данной реализации рекурсивный или явный стек в худшем случае может потребовать O(N) памяти. Обе реализации неустойчивые.')
page(); h('Контрольный тест на 50 элементах')
lines=(p/'demo.txt').read_text().splitlines()
para('Генератор mt19937, seed = 12. Числа выводятся с двумя знаками после запятой; внутри сортировки сохраняется исходная точность float.')
para('Исходный массив')
code('\n'.join(lines[2:12]),10)
para('Результат каждой из трёх сортировок')
code('\n'.join(lines[14:24]),10)
para('Все три результата полностью совпали с эталоном std::sort, включая повторяющиеся значения. Сравнение выполняется до округления для вывода. std::sort применяется только для проверки; исследуемые алгоритмы реализованы самостоятельно.')
h('Дополнительная проверка корректности')
para('Пройдено 109 тестовых массивов для каждого алгоритма: пустой, один элемент, два элемента, упорядоченный, обратный, одинаковые значения, повторы с отрицательными числами, границы диапазона, дробные значения и 100 случайных массивов разных размеров. Всего 327 проверок. Дополнительно проверен результат каждого из 15 измерений производительности.')
h('Сборка и запуск')
code('g++ -O2 -std=c++17 -Wall -Wextra -pedantic task2.cpp -o task2\n./task2 --demo\n./task2 --test\n./task2 --bench',9)
para('Режим --bench сохраняет timings.csv в текущую папку. Фиксированный seed обеспечивает повторяемость входных данных в использованной среде; время запусков может различаться.')
page(); h('Результаты измерений')
para('Среда: Linux x86_64, Intel Core i5-12450H, GCC 16.2.1. Сборка с -O2 и стандартом C++17. Измерение выполнено std::chrono::steady_clock; единица времени — миллисекунда.')
para('Для каждого N все три метода получают копии одного случайного массива с seed = 12. Генерация, копирование массива, вывод и проверка по std::sort находятся вне замеряемого участка. Измеряется один запуск каждого метода; результаты характеризуют этот опыт, а не статистически усреднённую производительность.')
t=d.add_table(rows=1,cols=6); t.autofit=False
widths=[4.5,2.6,2.6,2.6,2.6,2.6]
for c,w in zip(t.columns,widths): c.width=Cm(w)
headers=['Метод / N','1 000','10 000','100 000','500 000','1 000 000']
for c,txt in zip(t.rows[0].cells,headers): c.text=txt
for label,key in [('Быстрая без рекурсии','iterative_ms'),('Быстрая Хоара','hoare_ms'),('Вставками','insertion_ms')]:
 cells=t.add_row().cells
 for c,txt in zip(cells,[label]+[f"{float(r[key]):.3f}" for r in rows]): c.text=txt
for ri,row in enumerate(t.rows):
 for ci,c in enumerate(row.cells):
  c.width=Cm(widths[ci]); pr=c._tc.get_or_add_tcPr()
  borders=OxmlElement('w:tcBorders')
  for edge in ['top','left','bottom','right']:
   e=OxmlElement('w:'+edge); e.set(qn('w:val'),'single'); e.set(qn('w:sz'),'4'); e.set(qn('w:color'),'D9D9D9'); borders.append(e)
  pr.append(borders)
  if ri==0:
   e=OxmlElement('w:shd'); e.set(qn('w:fill'),'E6EDF5'); pr.append(e)
  for q in c.paragraphs:
   q.paragraph_format.space_before=Pt(5); q.paragraph_format.space_after=Pt(5)
   for r in q.runs: r.font.size=Pt(10); r.bold=ri==0
para('Все 15 отсортированных массивов совпали с эталоном. Значения таблицы получены реальным запуском программы, без расчётной экстраполяции.')
h('Анализ и выводы')
a=rows[-1]; ratio=float(a['insertion_ms'])/min(float(a['iterative_ms']),float(a['hoare_ms']))
para(f"При N = 1 000 000 сортировка вставками заняла {float(a['insertion_ms'])/1000:.2f} с. Это примерно в {ratio:.0f} раз дольше более быстрого из двух замеренных вариантов быстрой сортировки. Рост времени вставок согласуется с квадратичным характером числа сдвигов на случайных данных.")
para('Обе реализации быстрой сортировки значительно эффективнее вставок на больших случайных массивах. Их относительный порядок по времени может зависеть от размера массива, нагрузки системы и особенностей компиляции; одного замера недостаточно для вывода о постоянном превосходстве рекурсии или явного стека.')
para('Сортировка вставками полезна на небольших или почти упорядоченных данных. Проведённые функциональные проверки охватывают различные формы массивов, но таблица времени относится только к случайным данным заданного диапазона.')
